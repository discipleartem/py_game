MAIN_MENU = ("Выйти", "Новая Игра")

def show_main_menu():
    print("Главное меню:")

    # 1. Сначала нумеруем пункты меню через enumerate, сохраняя их оригинальные индексы.
    #    enumerate() добавляет счетчик к итерируемому объекту, возвращая кортежи вида (индекс, значение).
    #    Например, для MAIN_MENU это будет: (0, "Выйти"), (1, "Новая Игра").
    # 2. Превращаем результат в кортеж (tuple), чтобы иметь возможность использовать срезы (slicing).
    #    Кортеж выбран потому, что он неизменяем, что подходит для фиксированного списка меню.
    menu_items = tuple(enumerate(MAIN_MENU))

    # Организуем цикл так, чтобы пункт с индексом 0 ("Выйти") всегда шел последним:
    # - menu_items[1:] берет все элементы, начиная со второго (индексы 1, 2...).
    #   В данном случае это будет: ((1, "Новая Игра"),).
    # - menu_items[:1] берет только самый первый элемент (индекс 0).
    #   В данном случае это будет: ((0, "Выйти"),).
    # - Складывая их (+), мы получаем новый кортеж, где "Выйти" перемещен в конец.
    #   Результат: ((1, "Новая Игра"), (0, "Выйти")).
    #   Это обеспечивает, что "Выйти" всегда будет последним пунктом в отображаемом меню,
    #   независимо от его позиции в исходном MAIN_MENU.
    for i, item in menu_items[1:] + menu_items[:1]:
        # Выводим каждый пункт меню в формате "Индекс. Название пункта".
        print(f"{i}. {item}")